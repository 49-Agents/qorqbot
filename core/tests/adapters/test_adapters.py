    def native_codex_rewrite(self, original):
        # The rehearsal's native append shape, plus independently authored
        # provider/model/effort and unrelated MCP choices in this test only.
        lines = ['model = "user-selected-model"', 'model_provider = "user-provider"',
            'model_reasoning_effort = "high"', 'user_extra = [1, "two"]',
            original.decode(), '[tui]', 'screen_reader_detection_done = true']
        for event in ("PreToolUse", "PermissionRequest", "PostToolUse", "SessionStart",
                      "SessionEnd", "UserPromptSubmit", "Stop", "Interrupt"):
            name = str(self.roots.home / ".codex/hooks.json") + ":" + event + ":0:0"
            lines.extend(('[hooks.state.' + json.dumps(name) + ']', 'trusted_hash = "' + "a" * 64 + '"'))
        lines.extend(('[model_providers.user-provider]', 'name = "User provider"',
            'base_url = "http://127.0.0.1:39114/v1"', '[mcp_servers.unrelated]',
            'url = "http://127.0.0.1:39115/mcp"'))
        return ("\n".join(lines) + "\n").encode()

    def test_codex_native_choices_survive_new_runs_and_retries(self):
        data = self.data.model_copy(update={"hook_sink_argv": ("/synthetic/hook-sink",)})
        first = self.codex.prepare(data)
        config = self.roots.home / ".codex/config.toml"
        hooks = self.roots.home / ".codex/hooks.json"
        manifest = self.roots.workspace / ".qorqut/adapters/codex/preparation.json"
        initial_manifest = json.loads(manifest.read_bytes())
        self.assertIs(initial_manifest["codex_config_preserved"], False)
        # Legacy manifests and unmodified generated bytes still allow rotation.
        del initial_manifest["codex_config_preserved"]
        manifest.write_text(json.dumps(initial_manifest))
        data = data.model_copy(update={"core": data.core.model_copy(
            update={"url": "http://127.0.0.1:39116/mcp", "headers": (("X-Binding", "rotated"),)})})
        self.codex.prepare(data)
        self.assertEqual(tomllib.loads(config.read_text())["mcp_servers"]["qorqut-core"]["url"], data.core.url)
        self.assertIs(json.loads(manifest.read_bytes())["codex_config_preserved"], False)
        generated = config.read_bytes()
        rewritten = self.native_codex_rewrite(generated)
        config.write_bytes(rewritten)
        original_stat = config.stat()
        binding_bytes, old_hooks = first.binding_path.read_bytes(), hooks.read_bytes()
        new_run = self.run.model_copy(update={"run_id": uuid4(), "run_generation": 2})
        data = data.model_copy(update={"run": new_run})
        for _ in range(2):
            prepared = self.codex.prepare(data)
            self.assertEqual(config.read_bytes(), rewritten)
            self.assertEqual(config.stat().st_ino, original_stat.st_ino)
            self.assertEqual(config.stat().st_mtime_ns, original_stat.st_mtime_ns)
            self.assertEqual(json.loads(manifest.read_bytes())["files"]["home:.codex/config.toml"],
                hashlib.sha256(rewritten).hexdigest())
            self.assertIs(json.loads(manifest.read_bytes())["codex_config_preserved"], True)
            self.assertEqual(first.binding_path.read_bytes(), binding_bytes)
            self.assertNotEqual(hooks.read_bytes(), old_hooks)
            self.assertIn(str(prepared.binding_path), hooks.read_text())
        # A subsequent native trust rewrite is still owned-projection-equivalent.
        rewritten = rewritten.replace(b'a' * 64, b'b' * 64)
        config.write_bytes(rewritten)
        self.codex.prepare(data)
        self.assertEqual(config.read_bytes(), rewritten)
        self.assertEqual(json.loads(manifest.read_bytes())["files"]["home:.codex/config.toml"],
            hashlib.sha256(rewritten).hexdigest())
        for endpoint in (data.core.model_copy(update={"url": "http://127.0.0.1:39117/mcp"}),
                         data.core.model_copy(update={"headers": (("X-Binding", "another-rotation"),)})):
            before = {p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
            with self.assertRaisesRegex(AdapterError, "changed owned Codex"):
                self.codex.prepare(data.model_copy(update={"core": endpoint, "run": new_run.model_copy(
                    update={"run_id": uuid4(), "run_generation": 3})}))
            self.assertEqual({p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}, before)
        # Even a native/user edit back to the generated bytes does not reset mode.
        config.write_bytes(generated)
        self.codex.prepare(data)
        self.assertIs(json.loads(manifest.read_bytes())["codex_config_preserved"], True)
        with self.assertRaisesRegex(AdapterError, "changed owned Codex"):
            self.codex.prepare(data.model_copy(update={"core": endpoint}))
        # Only genuine absence permits a fresh generated file and resets mode.
        config.unlink()
        self.codex.prepare(data)
        self.assertEqual(config.read_bytes(), generated)
        self.assertIs(json.loads(manifest.read_bytes())["codex_config_preserved"], False)
        self.codex.prepare(data.model_copy(update={"core": endpoint}))
        self.assertEqual(tomllib.loads(config.read_text())["mcp_servers"]["qorqut-core"]["http_headers"], dict(endpoint.headers))
        # A changed managed hash takes the preservation path even when the
        # external edit happens to match the new desired generated bytes.
        config.write_bytes(config.read_bytes().replace(b"39116", b"39118"))
        self.codex.prepare(data.model_copy(update={"core": endpoint.model_copy(
            update={"url": "http://127.0.0.1:39118/mcp"})}))
        self.assertIs(json.loads(manifest.read_bytes())["codex_config_preserved"], True)

    def test_codex_native_config_conflicts_preflight_all_destinations(self):
        data = self.data.model_copy(update={"hook_sink_argv": ("/synthetic/hook-sink",)})
        prepared = self.codex.prepare(data)
        config = self.roots.home / ".codex/config.toml"
        manifest_path = self.roots.workspace / ".qorqut/adapters/codex/preparation.json"
        manifest = json.loads(manifest_path.read_bytes())
        generated = config.read_bytes()
        native = self.native_codex_rewrite(generated)
        next_data = data.model_copy(update={"run": self.run.model_copy(
            update={"run_id": uuid4(), "run_generation": 2})})

        def snapshot():
            return {p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}

        originals = snapshot()
        invalid = {
            "malformed": native + b"[broken\n",
            "invalid UTF-8": native + b"\xff",
            "approval": native.replace(b'approval_policy = "never"', b'approval_policy = "on-request"'),
            "sandbox": native.replace(b'sandbox_mode = "danger-full-access"', b'sandbox_mode = "read-only"'),
            "missing scalar": native.replace(b'approval_policy = "never"\n', b''),
            "missing table": native.replace(b'mcp_servers."qorqut-browser"', b'mcp_servers."different-browser"'),
            "missing owned key": native.replace(b'required = false\n', b''),
            "extra owned key": native.replace(b'required = false', b'required = false\nextra = "native"'),
            "extra nested key": native.replace(b'"Authorization" = ', b'"X-Extra" = "value"\n"Authorization" = '),
            "bool is not int": native.replace(b'required = false', b'required = 0'),
            "changed header": native.replace(b'Bearer synthetic-core', b'Bearer changed-core'),
        }
        for name, content in invalid.items():
            with self.subTest(conflict=name):
                config.write_bytes(content)
                before = snapshot()
                with self.assertRaises(AdapterError):
                    self.codex.prepare(next_data)
                self.assertEqual(snapshot(), before)
        config.write_bytes(native)
        for target in (self.roots.workspace / "AGENTS.md", self.roots.home / ".codex/hooks.json"):
            with self.subTest(conflict=target.name):
                target.write_bytes(b"unclaimed edit")
                before = snapshot()
                with self.assertRaises(AdapterError):
                    self.codex.prepare(next_data)
                self.assertEqual(snapshot(), before)
                target.write_bytes(originals[target])
        # The exception needs a valid existing manifest claim and both identities.
        for change in ("no manifest", "unclaimed config", "invalid hash", "invalid schema", "invalid marker", "home identity", "workspace identity"):
            with self.subTest(conflict=change):
                if change == "no manifest":
                    manifest_path.unlink()
                elif change in ("home identity", "workspace identity"):
                    root = self.roots.home if change == "home identity" else self.roots.workspace
                    (root / ".qorqut/adapters/identity.json").unlink()
                else:
                    modified = json.loads(json.dumps(manifest))
                    if change == "unclaimed config":
                        del modified["files"]["home:.codex/config.toml"]
                    elif change == "invalid hash":
                        modified["files"]["home:.codex/config.toml"] = "not-a-hash"
                    elif change == "invalid marker":
                        modified["codex_config_preserved"] = 0
                    else:
                        modified["schema_version"] = True
                    manifest_path.write_text(json.dumps(modified))
                before = snapshot()
                with self.assertRaises(AdapterError):
                    self.codex.prepare(next_data)
                self.assertEqual(snapshot(), before)
                for path, content in originals.items():
                    if path != config:
                        path.write_bytes(content)
        # A separately authored but semantically equivalent config is unclaimed.
        for path in prepared.generated_paths:
            if path != config:
                path.unlink()
        before = snapshot()
        with self.assertRaises(AdapterError):
            self.codex.prepare(data)
        self.assertEqual(snapshot(), before)

    def test_codex_native_config_race_never_overwrites_or_certifies_changed_bytes(self):
        data = self.data.model_copy(update={"hook_sink_argv": ("/synthetic/hook-sink",)})
        self.codex.prepare(data)
        config = self.roots.home / ".codex/config.toml"
        manifest = self.roots.workspace / ".qorqut/adapters/codex/preparation.json"
        native = self.native_codex_rewrite(config.read_bytes())
        read, write = ManagedTree.read, ManagedTree.atomic_write
        for stage in ("before writes", "after hooks"):
            with self.subTest(stage=stage):
                config.write_bytes(native)
                before = {p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
                raced = native + b"\n# concurrent native edit\n"
                next_data = data.model_copy(update={"run": self.run.model_copy(
                    update={"run_id": uuid4(), "run_generation": 2})})
                reads = 0

                def change_on_read(tree, path, *args, **kwargs):
                    nonlocal reads
                    if path == ".codex/config.toml":
                        reads += 1
                        if reads == 2:
                            config.write_bytes(raced)
                    return read(tree, path, *args, **kwargs)

                def change_after_hooks(tree, path, content):
                    write(tree, path, content)
                    if path == ".codex/hooks.json":
                        config.write_bytes(raced)

                method, replacement = ("read", change_on_read) if stage == "before writes" else ("atomic_write", change_after_hooks)
                with patch.object(ManagedTree, method, replacement), self.assertRaisesRegex(AdapterError, "changed during preparation"):
                    self.codex.prepare(next_data)
                self.assertEqual(config.read_bytes(), raced)
                self.assertEqual(manifest.read_bytes(), before[manifest])
                if stage == "before writes":
                    after = {p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
                    self.assertEqual(after, {**before, config: raced})
                # A new attempt validates the changed file; it never trusts a
                # hash sampled after the earlier validation.
                self.codex.prepare(next_data)
                self.assertEqual(config.read_bytes(), raced)
                self.assertEqual(json.loads(manifest.read_bytes())["files"]["home:.codex/config.toml"],
                    hashlib.sha256(raced).hexdigest())

        # The final replacement is a distinct window: its manifest may already
        # be installed, but preparation must not report success for raced bytes.
        validated = config.read_bytes()
        prior_manifest = manifest.read_bytes()
        self.assertIs(json.loads(prior_manifest)["codex_config_preserved"], True)
        incompatible = validated.replace(b'approval_policy = "never"', b'approval_policy = "on-request"')
        self.assertNotEqual(incompatible, validated)
        next_data = data.model_copy(update={"run": self.run.model_copy(
            update={"run_id": uuid4(), "run_generation": 3})})
        parent_stat = manifest.parent.stat()
        parent_identity = (parent_stat.st_dev, parent_stat.st_ino)
        replace, edits = os.replace, 0

        def change_during_manifest_replace(source, destination, *args, **kwargs):
            nonlocal edits
            result = replace(source, destination, *args, **kwargs)
            if destination == manifest.name and "dst_dir_fd" in kwargs:
                target = os.fstat(kwargs["dst_dir_fd"])
                if (target.st_dev, target.st_ino) == parent_identity:
                    config.write_bytes(incompatible)
                    edits += 1
            return result

        with patch("qorqut_core.adapters.managed_io.os.replace", side_effect=change_during_manifest_replace), \
                self.assertRaisesRegex(AdapterError, "changed during preparation"):
            self.codex.prepare(next_data)
        self.assertEqual(edits, 1)
        self.assertEqual(config.read_bytes(), incompatible)
        installed_manifest = manifest.read_bytes()
        self.assertNotEqual(installed_manifest, prior_manifest)
        recorded = json.loads(installed_manifest)
        self.assertIs(recorded["codex_config_preserved"], True)
        self.assertIs(recorded["native_verified"], False)
        self.assertEqual(recorded["files"]["home:.codex/config.toml"], hashlib.sha256(validated).hexdigest())
        self.assertNotEqual(recorded["files"]["home:.codex/config.toml"], hashlib.sha256(incompatible).hexdigest())
        before_retry = {p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        with self.assertRaisesRegex(AdapterError, "changed owned Codex"):
            self.codex.prepare(next_data)
        self.assertEqual({p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}, before_retry)
        recovered = validated + b"\n# harmless user edit retained after the conflict\n"
        config.write_bytes(recovered)
        self.codex.prepare(next_data)
        self.assertEqual(config.read_bytes(), recovered)
        recorded = json.loads(manifest.read_bytes())
        self.assertIs(recorded["codex_config_preserved"], True)
        self.assertEqual(recorded["files"]["home:.codex/config.toml"], hashlib.sha256(recovered).hexdigest())

    def test_long_history_manifest_compacts_without_changing_retained_bindings(self):
        for adapter in (self.claude, self.codex):
            with self.subTest(provider=adapter.provider):
                first = adapter.prepare(self.data)
                second_data = self.data.model_copy(update={"run": self.run.model_copy(
                    update={"run_id": uuid4(), "run_generation": 2})})
                second = adapter.prepare(second_data)
                retained = {result.binding_path: result.binding_path.read_bytes() for result in (first, second)}
                retained_stats = {path: path.stat() for path in retained}
                manifest_path = self.roots.workspace / f".qorqut/adapters/{adapter.provider}/preparation.json"
                legacy = json.loads(manifest_path.read_bytes())
                prefix = f"workspace:.qorqut/adapters/{adapter.provider}/runs/"
                first_key = prefix + str(self.run.run_id) + ".json"
                legacy["files"][first_key] = hashlib.sha256(retained[first.binding_path]).hexdigest()

                def encode(value):
                    return (json.dumps(value, sort_keys=True, ensure_ascii=False, indent=2) + "\n").encode()

                # Model a near-limit prior accumulated manifest without creating
                # thousands of sessions. Only the two retained bindings are real files.
                initial_size = len(encode(legacy))
                legacy["files"][prefix + str(UUID(int=1)) + ".json"] = "0" * 64
                entry_size = len(encode(legacy)) - initial_size
                count = (GENERATED_FILE_LIMIT - initial_size) // entry_size
                for number in range(2, count + 1):
                    legacy["files"][prefix + str(UUID(int=number)) + ".json"] = "0" * 64
                accumulated = encode(legacy)
                self.assertLessEqual(len(accumulated), GENERATED_FILE_LIMIT)
                self.assertGreater(len(accumulated), GENERATED_FILE_LIMIT - entry_size)
                manifest_path.write_bytes(accumulated)
                current_data = self.data.model_copy(update={"run": self.run.model_copy(
                    update={"run_id": uuid4(), "run_generation": 3})})
                current = adapter.prepare(current_data)
                retained[current.binding_path] = current.binding_path.read_bytes()
                retained_stats[current.binding_path] = current.binding_path.stat()
                compacted = manifest_path.read_bytes()
                self.assertLess(len(compacted), 16 * 1024)
                current_manifest = json.loads(compacted)
                self.assertEqual([key for key in current_manifest["files"] if key.startswith(prefix)],
                    [prefix + str(current_data.run.run_id) + ".json"])
                adapter.prepare(current_data)
                self.assertEqual(manifest_path.read_bytes(), compacted)

                # Old manifest membership is not authority to alter a binding.
                self.assertNotIn(first_key, current_manifest["files"])
                wrong_prior = self.data.model_copy(update={"run": self.run.model_copy(
                    update={"environment_generation": 2})})
                with self.assertRaisesRegex(AdapterError, "binding is immutable"):
                    adapter.prepare(wrong_prior)
                self.assertEqual(manifest_path.read_bytes(), compacted)
                adapter.prepare(self.data)  # Exact retained prior run is still preparable.
                prior_manifest = manifest_path.read_bytes()
                self.assertLess(len(prior_manifest), 16 * 1024)
                adapter.prepare(self.data)
                self.assertEqual(manifest_path.read_bytes(), prior_manifest)
                for path, original in retained.items():
                    self.assertEqual(path.read_bytes(), original)
                    before, after = retained_stats[path], path.stat()
                    self.assertEqual((after.st_dev, after.st_ino, after.st_mtime_ns),
                        (before.st_dev, before.st_ino, before.st_mtime_ns))

